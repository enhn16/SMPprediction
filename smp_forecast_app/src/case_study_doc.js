function table(cols, rows, widths, hl) {
  const ws = widths.map((x) => Math.round((x / widths.reduce((a, c) => a + c, 0)) * W));
  ws[ws.length - 1] += W - ws.reduce((a, c) => a + c, 0);
  return new Table({
    width: { size: W, type: WidthType.DXA }, columnWidths: ws,
    rows: [new TableRow({ tableHeader: true, children: cols.map((c, i) => cell(c, ws[i], true)) }),
      ...rows.map((r, ri) => new TableRow({ children: r.map((c, i) => cell(c, ws[i], false, hl && hl(r, ri) ? "FFF2CC" : undefined)) }))],
  });
}
